<?php

require_once __DIR__.'/vendor/autoload.php';

use PhpParser\Error;
use PhpParser\Node;
use PhpParser\NodeTraverser;
use PhpParser\NodeVisitor\NameResolver;
use PhpParser\NodeVisitorAbstract;
use PhpParser\ParserFactory;

class ClassNameVisitor extends NodeVisitorAbstract
{
    private array $classMap = [];

    private array $seenNames = [];

    #[Override]
    public function enterNode(Node $node): ?Node
    {
        if (!$node instanceof Node\Stmt\ClassLike || null === $node->name) {
            return null;
        }

        $name = $node->name->toString();
        if (!\str_starts_with($name, 'Swift_') || $node->namespacedName->toString() !== $name) {
            return null;
        }
        $key = \strtolower($name);
        if (isset($this->seenNames[$key])) {
            throw new RuntimeException('Duplicate declaration for '.$name);
        }
        $this->seenNames[$key] = true;
        $this->classMap[$name] = \str_replace('_', '\\', $name);

        return null;
    }

    public function getClassMap(): array
    {
        \ksort($this->classMap, \SORT_STRING);

        return $this->classMap;
    }
}

function generateClassMap(string ...$directories): array
{
    $parser    = (new ParserFactory())->createForHostVersion();
    $traverser = new NodeTraverser();
    $visitor   = new ClassNameVisitor();
    $traverser->addVisitor(new NameResolver());
    $traverser->addVisitor($visitor);

    $files = [];
    foreach ($directories as $directory) {
        $iterator = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($directory, FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $file) {
            if ($file->isFile() && 'php' === $file->getExtension()) {
                $files[$file->getRealPath()] = $file->getPathname();
            }
        }
    }
    \ksort($files, \SORT_STRING);
    foreach ($files as $file) {
        $code = @\file_get_contents($file);
        if (false === $code) {
            throw new RuntimeException('Unable to read '.$file);
        }
        try {
            $traverser->traverse($parser->parse($code) ?? []);
        } catch (Error $error) {
            throw new RuntimeException('Parse error in '.$file.': '.$error->getMessage(), 0, $error);
        }
    }

    return $visitor->getClassMap();
}

/** Generate both committed outputs from the same complete, sorted source map. */
function writeGeneratedClassMaps(string $root, string ...$directories): int
{
    $classMap   = \generateClassMap(...$directories);
    $width      = 0;
    $aliasWidth = 0;
    foreach ($classMap as $name => $alias) {
        $width      = \max($width, \strlen(\var_export($name, true)));
        $aliasWidth = \max($aliasWidth, \strlen(\var_export(\strtolower($alias), true)));
    }

    // class_aliases.php is keyed by lower-case alias because PHP class names are case-insensitive.
    $mapLines   = '';
    $aliasLines = '';
    foreach ($classMap as $name => $alias) {
        $mapLines   .= '    '.\str_pad(\var_export($name, true), $width).' => '.\var_export($alias, true).",\n";
        $aliasLines .= '    '.\str_pad(\var_export(\strtolower($alias), true), $aliasWidth).' => '.\var_export($name, true).",\n";
    }
    $map     = "<?php\n\n".([] === $classMap ? "return [];\n" : "return [\n".$mapLines."];\n");
    $aliases = "<?php\n\n// Auto-generated namespace aliases for forward-compatible usage.\n"
        ."// e.g. Swift\\Message can be used instead of Swift_Message.\n"
        ."// Lower-case alias => original class. Swift::registerAliases() declares each alias\n"
        ."// on first use, so loading this map loads no Swift class.\n"
        ."// Generated by: php generate_class_map.php\n\n"
        .([] === $classMap ? "return [];\n" : "return [\n".$aliasLines."];\n");

    foreach ([$root.'/class_map.php' => $map, $root.'/lib/class_aliases.php' => $aliases] as $path => $contents) {
        if (\strlen($contents) !== @\file_put_contents($path, $contents, \LOCK_EX)) {
            throw new RuntimeException('Unable to write '.$path);
        }
    }

    return \count($classMap);
}

if (__FILE__ === \realpath($_SERVER['SCRIPT_FILENAME'] ?? '')) {
    try {
        $count = \writeGeneratedClassMaps(__DIR__, __DIR__.'/lib');
        \fwrite(\STDOUT, \sprintf("Generated class map and namespace aliases with %d entries.\n", $count));
    } catch (Throwable $error) {
        \fwrite(\STDERR, 'Class map generation failed: '.$error->getMessage()."\n");
        exit(1);
    }
}
